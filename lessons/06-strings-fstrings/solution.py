# Strings and f-strings
player = "Warrior"
print("It's my turn")
print(player + " the Brave")
print("=" * 20)
print(len(player))

level = 7
print(f"{player} is level {level}")
print(f"New level: {level + 1}")
price = 4.5
print(f"Potion: {price:.2f} gold")

laugh = "ha" * 3
print(f"{laugh} has {len(laugh)} letters")
